test("multi-field apply validates the entire patch before changing any stored field", function()
  local _, _, profiles, saved = fixture(); local before = profiles:Capture()
  eq(profiles:Apply(before, { count = 2, scale = 999 }), false)
  eq(saved.profiles.global.count, nil); eq(saved.profiles.global.scale, nil)
  eq(profiles:Apply(before, { count = 2, scale = 0.75 }), true)
  eq(saved.profiles.global.count, 2); eq(saved.profiles.global.scale, 0.75)
end)
