  eq(history:GetStatus().undo, 0); eq(history:Undo(), false); eq(model:Get().count, 3)
end)
test("unexpected direct storage changes are detected by the expected snapshot guard", function()
  local history, model, _, saved = fixture()
  history:Execute("count", 2); saved.profiles.global.count = 3
  eq(history:Undo(), false); eq(saved.profiles.global.count, 3); eq(model:Get().count, 3)
end)
